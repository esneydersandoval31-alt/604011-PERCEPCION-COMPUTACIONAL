# 1. PROCESAMIENTO TRADICIONAL DE IMÁGENES CON OPENCV
# ------------------------------------------------------------------------------
def aplicar_procesamiento_pdi(image_path):
    """
    Carga una imagen, aplica un desenfoque Gaussiano para reducir ruido,
    y luego calcula filtros Sobel, Canny y Detección de Contornos.
    """
    # Cargar en escala de grises
    img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
    if img is None:
        raise FileNotFoundError(f"No se pudo cargar la imagen en: {image_path}")

    # Redimensionar para consistencia
    img = cv2.resize(img, (256, 256))

    # --- NUEVO PASO: Desenfoque Gaussiano para reducir ruido ---
    # Usamos un kernel de 5x5 con desviación estándar automática
    img_blurred = cv2.GaussianBlur(img, (5, 5), 0)

    # A. Filtro Sobel (Gradientes X e Y) aplicado sobre la imagen suavizada
    sobelx = cv2.Sobel(img_blurred, cv2.CV_64F, 1, 0, ksize=3)
    sobely = cv2.Sobel(img_blurred, cv2.CV_64F, 0, 1, ksize=3)
    sobel_combined = cv2.magnitude(sobelx, sobely)
    sobel_combined = np.uint8(np.clip(sobel_combined, 0, 255))

    # B. Detección de Bordes Canny sobre la imagen suavizada
    canny_edges = cv2.Canny(img_blurred, threshold1=50, threshold2=150)

    # C. Detección de Contornos
    contours, _ = cv2.findContours(canny_edges, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    img_contours = cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
    cv2.drawContours(img_contours, contours, -1, (0, 255, 0), 2)

    return img, sobel_combined, canny_edges, img_contours


# 2. EVALUACIÓN DE CALIDAD DE IMAGEN (MSE, PSNR, SSIM)
# ------------------------------------------------------------------------------
def calcular_mse(img_orig, img_proc):
    """Calcula el Error Cuadrático Medio (MSE)"""
    return np.mean((img_orig.astype("float") - img_proc.astype("float")) ** 2)

def calcular_psnr(img_orig, img_proc):
    """Calcula la Relación Señal-Ruido Pico (PSNR)"""
    mse = calcular_mse(img_orig, img_proc)
    if mse == 0:
        return float('inf')
    max_pixel = 255.0
    return 20 * np.log10(max_pixel / np.sqrt(mse))

def calcular_ssim(img_orig, img_proc):
    """Calcula el Índice de Similitud Estructural (SSIM)"""
    return ssim(img_orig, img_proc, data_range=img_proc.max() - img_proc.min())

def evaluar_calidad(img_original, img_ruidosa_o_comprimida):
    """Retorna un diccionario con todas las métricas de calidad"""
    mse_val = calcular_mse(img_original, img_ruidosa_o_comprimida)
    psnr_val = calcular_psnr(img_original, img_ruidosa_o_comprimida)
    ssim_val = calcular_ssim(img_original, img_ruidosa_o_comprimida)

    print("\n--- MÉRITAS DE CALIDAD DE IMAGEN ---")
    print(f"MSE  (Mean Squared Error)         : {mse_val:.4f} (Menor es mejor)")
    print(f"PSNR (Peak Signal-to-Noise Ratio) : {psnr_val:.2f} dB (Mayor es mejor)")
    print(f"SSIM (Structural Similarity)      : {ssim_val:.4f} (Cercano a 1 es mejor)")

    return {"MSE": mse_val, "PSNR": psnr_val, "SSIM": ssim_val}


# 3. RED NEURONAL CONVOLUCIONAL (CNN) CON TENSORFLOW / KERAS
# ------------------------------------------------------------------------------
def construir_y_entrenar_cnn():
    """
    Crea una arquitectura CNN moderna y entrena con el dataset CIFAR-10.
    """
    print("\n--- CARGANDO DATASET Y CONSTRUYENDO LA CNN ---")
    # Cargar dataset de ejemplo
    (X_train, y_train), (X_test, y_test) = font_tf.keras.datasets.cifar10.load_data()
    X_train, X_test = X_train / 255.0, X_test / 255.0  # Normalización [0, 1]

    class_names = ['Avión', 'Auto', 'Pájaro', 'Gato', 'Ciervo',
                   'Perro', 'Rana', 'Caballo', 'Barco', 'Camión']

    # Arquitectura de la Red Neuronal Convolucional
    model = models.Sequential([
        # Capa Convolucional 1 + Pooling
        layers.Conv2D(32, (3, 3), activation='relu', padding='same', input_shape=(32, 32, 3)),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),

        # Capa Convolucional 2 + Pooling
        layers.Conv2D(64, (3, 3), activation='relu', padding='same'),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),

        # Capa Convolucional 3
        layers.Conv2D(64, (3, 3), activation='relu', padding='same'),

        # Aplanado y Capas Densas (Clasificación)
        layers.Flatten(),
        layers.Dense(64, activation='relu'),
        layers.Dropout(0.3),
        layers.Dense(10, activation='softmax')
    ])

    model.compile(optimizer='adam',
                  loss='sparse_categorical_crossentropy',
                  metrics=['accuracy'])

    model.summary()

    # Entrenamiento rápido de demostración (5 épocas)
    history = model.fit(X_train, y_train, epochs=5,
                        validation_data=(X_test, y_test), batch_size=64)

    test_loss, test_acc = model.evaluate(X_test, y_test, verbose=2)
    print(f"\nPrecisión en Test: {test_acc*100:.2f}%")

    return model, history, (X_test, y_test), class_names


