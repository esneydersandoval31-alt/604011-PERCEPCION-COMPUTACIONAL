# 1. Preparar la imagen del panda rojo como entrada para la red
img_raw = cv2.imread("panda_rojo.jpg")
img_rgb = cv2.cvtColor(img_raw, cv2.COLOR_BGR2RGB)
img_resized = cv2.resize(img_rgb, (128, 128))  # Redimensionar a 128x128 para entrenamiento

# Normalizar la imagen a rango [0, 1] y agregar la dimensión del lote (batch dimension)
x_train_panda = np.expand_dims(img_resized / 255.0, axis=0)

# 2. Construir un Autoencoder Convolucional Simple
# La red intentará mapear la imagen a sí misma aprendiendo sus filtros espaciales
autoencoder = models.Sequential([
    # --- Codificador (Encoder) ---
    layers.Input(shape=(128, 128, 3)),
    layers.Conv2D(16, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2), padding='same'),
    layers.Conv2D(8, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2), padding='same'),

    # --- Decodificador (Decoder) ---
    layers.Conv2DTranspose(8, (3, 3), activation='relu', padding='same'),
    layers.UpSampling2D((2, 2)),
    layers.Conv2DTranspose(16, (3, 3), activation='relu', padding='same'),
    layers.UpSampling2D((2, 2)),
    layers.Conv2D(3, (3, 3), activation='sigmoid', padding='same')
])

autoencoder.compile(optimizer='adam', loss='mean_squared_error')
autoencoder.summary()

# 3. Entrenar el modelo para reconstruir el panda rojo (overfitting de demostración)
print("\n--- ENTRENANDO LA CNN CON EL PANDA ROJO ---")
history = autoencoder.fit(x_train_panda, x_train_panda, epochs=150, verbose=0) # Entrenar por 150 épocas en silencio
print(f"Entrenamiento finalizado. Pérdida final (Loss): {history.history['loss'][-1]:.6f}")

# 4. Pasar la imagen por el modelo entrenado
img_reconstruida = autoencoder.predict(x_train_panda)[0]

